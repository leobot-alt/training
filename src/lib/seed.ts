import type { Candidato, CandidatoStatus, Documento } from './types';

const DAY = 86_400_000;

const daysAgo = (days: number, hour = 10) => {
  const date = new Date(Date.now() - days * DAY);
  date.setHours(hour, 0, 0, 0);
  return date.toISOString();
};

const docs = (validados: number, enviados: number): Documento[] => {
  const base = [
    'Registro profissional (CRP/CRM)',
    'Diploma de graduação',
    'Comprovante de residência',
    'Documento de identidade (RG/CNH)',
    'Certificado de especialização',
  ];
  return base.map((nome, index) => ({
    nome,
    status: index < validados ? 'validado' : index < validados + enviados ? 'enviado' : 'pendente',
  }));
};

