export function buildSeed(): Candidato[] {
  return raw.map((item, index) => {
    const criadoEm = daysAgo(item.dias, 9 + (index % 8));
    const notas = index % 3 === 0
      ? [
          {
            id: `nota-${index}-1`,
            autor: 'Equipe de Recrutamento',
            texto: notasPool[index % notasPool.length],
            em: daysAgo(Math.max(0, Math.floor(item.dias / 3)), 14),
          },
        ]
      : [];

    return {
      id: `cand-${String(index + 1).padStart(3, '0')}`,
      protocolo: `SOM-${String(2400 + index)}`,
      nome: item.nome,
      email: item.email,
      telefone: item.telefone,
      cidade: item.cidade,
      uf: item.uf,
      profissao: item.profissao,
      registro: item.registro,
      especialidades: item.especialidades,
      abordagem: item.abordagem,
      experienciaAnos: item.experienciaAnos,
      modalidade: item.modalidade,
      turnos: item.turnos,
      valorSessao: item.valorSessao,
      status: item.status as CandidatoStatus,
            origem: item.origem,
      criadoEm,
      atualizadoEm: daysAgo(Math.max(0, Math.floor(item.dias / 2)), 16),
      notas,
      documentos: docs(item.docs[0], item.docs[1]),
      tags: item.tags,
      lgpd: item.lgpd,
      bio: item.bio,
    };
  });
}
